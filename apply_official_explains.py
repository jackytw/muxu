import os
EXCEL = os.path.join(r"D:\devs\muxu", "安全性設定_群組原則.xlsx")
wb = openpyxl.load_workbook(EXCEL)

def make_note_style(cell, alt):
    cell.font      = NOTE_F
    cell.fill      = NOTE_FILL if alt else NOTE_ALT
    cell.alignment = LEFT
    cell.border    = BORDER

def best_match(name):
    """精確匹配或最長前綴匹配。"""
    name = name.strip()
    if name in OFFICIAL:
        return OFFICIAL[name]
    # 嘗試去掉全形冒號後的修飾語
    base = re.sub(r'（.*?）$', '', name).strip()
    if base in OFFICIAL:
        return OFFICIAL[base]
    # 找最長 key 是 name 的前綴
    candidates = [(k, v) for k, v in OFFICIAL.items()
                  if name.startswith(k) or k.startswith(name)]
    if candidates:
        return max(candidates, key=lambda x: len(x[0]))[1]
    return None

updated = 0
for ws in wb.worksheets:
    if ws.title == "總索引":
        continue
    for row in ws.iter_rows():
        # 找 A 欄的原則名稱 (跳過 section/subsection 合併列)
        a_cell = row[0]
        if a_cell.value is None:
            continue
        name = str(a_cell.value).strip()
        if len(name) < 2:
            continue
        official = best_match(name)
        if not official:
            continue
        # 找 E 欄（第 5 格）
        if len(row) < 5:
            continue
        e_cell = row[4]
        if e_cell.value == official:
            continue
        e_cell.value = official
        alt = (a_cell.row % 2 == 0)
        make_note_style(e_cell, alt)
        # 調整列高
        lines = max(3, -(-len(official) // 46))
        ws.row_dimensions[a_cell.row].height = max(48, lines * 15)
        updated += 1

wb.save(EXCEL)
print(f"已更新 {updated} 個儲存格的官方解說。")
