import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

wb = openpyxl.Workbook()

HEADER_FILL  = PatternFill("solid", start_color="1F3864")
SECTION_FILL = PatternFill("solid", start_color="2E75B6")
SUB_FILL     = PatternFill("solid", start_color="BDD7EE")
ROW_ALT_FILL = PatternFill("solid", start_color="EBF3FB")
NOTE_FILL    = PatternFill("solid", start_color="FFF2CC")
NOTE_ALT     = PatternFill("solid", start_color="FFFEF5")

WHITE  = Font(name="Arial", bold=True, color="FFFFFF", size=10)
DARK   = Font(name="Arial", bold=True, color="1F3864", size=10)
NORMAL = Font(name="Arial", size=10)
NOTE_F = Font(name="Arial", size=10, color="7B3F00")
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)
LEFT   = Alignment(horizontal="left",   vertical="center", wrap_text=True)
thin   = Side(style="thin", color="B0C4DE")
BORDER = Border(left=thin, right=thin, top=thin, bottom=thin)
NCOLS  = 5

def hdr(ws, row, col, val):
    c = ws.cell(row=row, column=col, value=val)
    c.font = WHITE; c.fill = HEADER_FILL
    c.alignment = CENTER; c.border = BORDER

def section(ws, row, label):
    c = ws.cell(row=row, column=1, value=label)
    c.font = WHITE; c.fill = SECTION_FILL
    c.alignment = LEFT; c.border = BORDER
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=NCOLS)
    ws.row_dimensions[row].height = 20

def subsection(ws, row, label):
    c = ws.cell(row=row, column=1, value=label)
    c.font = DARK; c.fill = SUB_FILL
    c.alignment = LEFT; c.border = BORDER
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=NCOLS)
    ws.row_dimensions[row].height = 18

def row_data(ws, row, cols, alt=False):
    for ci, val in enumerate(cols, 1):
        c = ws.cell(row=row, column=ci, value=val)
        if ci == NCOLS:
            c.font = NOTE_F
            c.fill = NOTE_FILL if alt else NOTE_ALT
        else:
            c.font = NORMAL
            c.fill = ROW_ALT_FILL if alt else PatternFill("solid", start_color="FFFFFF")
        c.alignment = LEFT; c.border = BORDER
    # 依解說欄位字數估算所需列高（欄寬約 52 字元，每行約 15pt）
    note = str(cols[NCOLS - 1]) if len(cols) >= NCOLS and cols[NCOLS - 1] else ""
    lines = max(2, -(-len(note) // 46))  # ceiling division
    ws.row_dimensions[row].height = max(42, lines * 16)

def setup(ws, widths):
    ws.sheet_view.showGridLines = False
    for ltr, w in widths.items():
        ws.column_dimensions[ltr].width = w
    for col, lbl in enumerate(["名稱","描述","原則","安全性設定值","解說"], 1):
        hdr(ws, 1, col, lbl)
    ws.freeze_panes = "A2"

